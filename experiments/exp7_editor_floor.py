"""Experiment 7 — is the editor floor a capacity limit or a training budget?

exp4 gated on byte-identical block restore, which a masked-diffusion infill can
never satisfy: it regenerates the span instead of copying it, so the number is
0.000 at every budget and the gate can never open. That made an undertrained
preset look like an architecture failure. This experiment measures the two
things that were conflated:

    copy fidelity   byte-identical restore (diagnostic, not a gate)
    task ability    does the generated block parse, support the document's
                    thesis, and restore specificity?

and does it as a function of the number of optimizer steps, on both the
clean-block sanity task and the actual local / cross-block repair tasks.

The no-op baseline is measured on the same tasks. It matters because a clean
block already parses and a locally-degraded block already carries the right
thesis: those metrics can be high without the model doing anything.

Pre-registered reading, written before the run:

  * ability rises with budget, then plateaus or falls  -> the floor is a
    budget artefact of the smoke preset; report the budget needed, do not
    report an architecture limit.
  * ability stays 0.000 at every budget                -> the backbone or the
    objective is wrong for this task, and that is the finding.
  * ability rises but specificity stays 0.000          -> the editor can
    restore coherence but not specificity, which is a different (and narrower)
    result than "the editor cannot edit".

The output is `results/exp7_editor_floor.json`; the table is generated by
aggregate.py like every other number.
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from _common import (arg_parser, banner, get_system, table, write_result)
from cgr.config import Config
from cgr.data.corpus import build_corpus
from cgr.data.documents import (block_quality, coherence, make_task_set,
                                quality, task_from_blocks)
from cgr.data.grammar import blocked_spans, parse_block
from cgr.train import train

PREDICTION = {
    "budget_artefact": "task ability rises with optimizer steps, then "
                       "plateaus or falls; specificity may stay at zero",
    "capacity_limit": "task ability stays 0.000 at every budget",
    "coherence_without_specificity": "c_edit rises but quality stays 0.000",
    "copy_fidelity_is_not_a_gate": "byte-identical restore is ~0.000 at every "
                                   "budget and is reported only as a "
                                   "diagnostic",
}


def parse_budgets(s: str) -> list[tuple[int, int]]:
    out = []
    for part in s.split(","):
        a, b = part.split(":")
        out.append((int(a), int(b)))
    return out


def diagnose(system, cfg, tok, splits, n: int, seed: int,
             split: str = "test") -> dict:
    system.eval()
    recs = splits[split]
    if not recs:
        raise SystemExit(
            f"split {split!r} is empty. `unseen` requires "
            f"DataConfig.n_heldout_theses > 0 and an open-vocabulary "
            f"tokenizer (the `diffugpt` preset sets both).")

    # ---- 1. clean-block infill sanity ---------------------------------
    exact = parse_ok = thesis_ok = specific = 0
    sanity = recs[:n]
    for r in sanity:
        new = system.repair(r.blocks, 1, mode="local", steps=6, seed=seed)
        gen = new[1]
        exact += int(gen.strip() == r.blocks[1].strip())
        tid, _, _ = parse_block(gen, "body")
        parse_ok += int(tid is not None)
        thesis_ok += int(tid == r.thesis_id)
        blocks = task_from_blocks(new, r.thesis_id).blocks
        specific += int(block_quality(blocks[1], r.thesis_id) == 1)
    m = max(len(sanity), 1)

    # ---- 2. no-op baseline on the same clean blocks -------------------
    noop_parse = noop_thesis = 0
    for r in sanity:
        tid, _, _ = parse_block(r.blocks[1], "body")
        noop_parse += int(tid is not None)
        noop_thesis += int(tid == r.thesis_id)

    # ---- 3. the actual repair tasks -----------------------------------
    stats: dict = {}
    tasks = make_task_set(
        recs, n, seed=seed,
        fits=lambda blocks: len(blocked_spans(blocks, tok)[0])
        <= cfg.model.max_len, stats=stats)

    def score(task, blocks_text: list[str],
              specificity_defined: bool = True) -> tuple[float, float | None]:
        """Coherence and specificity on the blocks the task actually edits.

        Scoring the whole document would credit the untouched siblings: on a
        local defect the other bodies are still specific, so a degenerate edit
        inherits their quality. The edited blocks are the only honest unit.

        On the `unseen` split a local defect's specificity is undefined: the
        degraded block's reason was replaced and the thesis's reason pool never
        appeared in training. It is returned as None, not 0, for the same
        reason exp4 does it.
        """
        blocks = task_from_blocks(blocks_text, task.authoritative).blocks
        idx = task.edited or [task.target_block]
        c = sum(1 for i in idx
                if blocks[i].thesis_id == task.authoritative) / len(idx)
        if not specificity_defined:
            return c, None
        q = sum(block_quality(blocks[i], task.authoritative)
                for i in idx) / len(idx)
        return c, q

    repair = {}
    for defect, mode in (("local", "local"),
                         ("cross_block", "editable"),
                         ("cross_block_partial", "editable")):
        spec_ok = not (split == "unseen" and defect == "local")
        rows = []
        for task in tasks[defect]:
            before_c, before_q = score(task, task.corrupt_blocks, spec_ok)
            target = task.target_block
            new = system.repair(task.corrupt_blocks, target, mode=mode,
                                steps=6, seed=seed)
            c, q = score(task, new, spec_ok)
            rows.append({"before_c": before_c, "before_q": before_q,
                         "c_edit": c, "quality": q})
        m2 = max(len(rows), 1)
        qs = [r["quality"] for r in rows if r["quality"] is not None]
        bq = [r["before_q"] for r in rows if r["before_q"] is not None]
        repair[defect] = {
            "n": len(rows),
            "noop_c_edit": sum(r["before_c"] for r in rows) / m2,
            "noop_quality": (sum(bq) / len(bq)) if bq else None,
            "c_edit": sum(r["c_edit"] for r in rows) / m2,
            "quality": (sum(qs) / len(qs)) if qs else None,
            "n_quality": len(qs),
            "c_edit_1": sum(1 for r in rows if r["c_edit"] == 1.0) / m2,
        }

    return {
        "infill": {"exact": exact / m, "parses": parse_ok / m,
                   "on_thesis": thesis_ok / m, "specific": specific / m,
                   "noop_parses": noop_parse / m,
                   "noop_on_thesis": noop_thesis / m},
        "repair": repair,
        "tasks": {"scanned": stats.get("scanned"),
                  "skipped": stats.get("skipped")},
    }


def main() -> int:
    ap = arg_parser("Experiment 7: editor floor vs training budget")
    ap.add_argument("--budgets", default="2:1,10:5,20:10,40:20",
                    help="comma-separated stage_a:stage_b epoch budgets")
    ap.add_argument("--reuse", action="store_true", default=True,
                    help="reuse checkpoints/floor_a{a}_b{b} when present")
    args = ap.parse_args()
    n = args.n or 10
    budgets = parse_budgets(args.budgets)

    banner("Experiment 7 — editor floor: capacity or budget?")
    base = Config.preset(args.preset)
    tok, splits = build_corpus(base)

    rows = []
    for a, b in budgets:
        out = Path("checkpoints") / f"floor_a{a}_b{b}"
        ckpt = out / "stage_b.pt"
        if not (args.reuse and ckpt.exists()):
            cfg = Config.preset(args.preset)
            cfg.train.stage_a_epochs = a
            cfg.train.stage_b_epochs = b
            cfg.train.seed = args.seed
            t0 = time.time()
            train(cfg, out, verbose=False)
            secs = round(time.time() - t0, 1)
        else:
            secs = None
        system, cfg = get_system(args.preset, seed=args.seed,
                                 checkpoint=str(ckpt), verbose=False)
        d = diagnose(system, cfg, system.tok, splits, n=n, seed=args.seed,
                     split=args.split)
        steps = (a + b) * (400 // cfg.train.batch_size)
        row = {"budget": f"{a}+{b}", "opt_steps": steps,
               "train_secs": secs, **d["infill"], **d["tasks"],
               "local_c_edit": d["repair"]["local"]["c_edit"],
               "local_noop_c_edit": d["repair"]["local"]["noop_c_edit"],
               "local_quality": d["repair"]["local"]["quality"],
               "local_noop_quality": d["repair"]["local"]["noop_quality"],
               "cross_c_edit": d["repair"]["cross_block"]["c_edit"],
               "cross_noop_c_edit": d["repair"]["cross_block"]["noop_c_edit"],
               "cross_quality": d["repair"]["cross_block"]["quality"],
               "cross_noop_quality": d["repair"]["cross_block"]["noop_quality"],
               "partial_c_edit": d["repair"]["cross_block_partial"]["c_edit"],
               "partial_noop_c_edit":
                   d["repair"]["cross_block_partial"]["noop_c_edit"],
               "partial_quality":
                   d["repair"]["cross_block_partial"]["quality"],
               "partial_noop_quality":
                   d["repair"]["cross_block_partial"]["noop_quality"]}
        rows.append(row)
        print(json.dumps({k: v for k, v in row.items()
                          if k in ("budget", "opt_steps", "on_thesis",
                                   "specific", "local_c_edit",
                                   "local_quality", "cross_c_edit",
                                   "cross_quality", "partial_c_edit",
                                   "partial_quality")}))

    table(rows, ["budget", "opt_steps", "exact", "parses", "on_thesis",
                 "specific", "local_c_edit", "local_quality", "cross_c_edit",
                 "cross_quality", "partial_c_edit", "partial_quality"])

    best = max(rows, key=lambda r: r["on_thesis"])
    ability_rises = best["on_thesis"] > 0.2
    specificity_rises = max(r["specific"] for r in rows) > 0.0
    local_repair_rises = max((r["local_quality"] or 0.0) for r in rows) > 0.0
    # Same 0.2 ability threshold as exp4's precondition. A cross-block c_target
    # of 0.07 is ~3 of 40 edited blocks: above the no-op floor of 0, but not a
    # repair. Calling that "rises" would let noise open the gate.
    cross_repair_rises = max(r["cross_c_edit"] for r in rows) >= 0.2
    partial_repair_rises = max(r["partial_c_edit"] for r in rows) >= 0.2

    notes = []
    if not ability_rises:
        notes.append(
            "CAPACITY/OBJECTIVE FINDING: on-thesis infill stays at or below "
            "0.2 at every budget tested. The backbone or the denoising "
            "objective is wrong for this task, not merely undertrained.")
    else:
        notes.append(
            f"BUDGET, NOT CAPACITY: on-thesis infill rises to "
            f"{best['on_thesis']:.0%} at {best['budget']} "
            f"({best['opt_steps']} optimizer steps), from "
            f"{rows[0]['on_thesis']:.0%} at {rows[0]['budget']} "
            f"({rows[0]['opt_steps']} steps). The smoke preset's 75 steps are "
            f"below the ability floor; the earlier 0.000 was a property of the "
            f"budget, not of the architecture.")
    if ability_rises and not specificity_rises:
        notes.append(
            "COHERENCE WITHOUT SPECIFICITY: the editor produces parseable, "
            "on-thesis blocks but never a specific reason (quality 0.000 at "
            "every budget). This is a narrower and more useful result than "
            "'the editor cannot edit': it can restore label consistency, and "
            "it cannot restore the specificity that defines the local defect. "
            "A local-repair claim needs the specificity number, not c_edit.")
    if ability_rises and not local_repair_rises:
        if args.split == "unseen":
            notes.append(
                "Local specificity is undefined on the unseen split and is "
                "reported as None, not 0: the degraded block's reason was "
                "replaced and the unseen thesis's reason pool never appeared "
                "in training. The local row's c_edit is still defined, but it "
                "cannot distinguish a repair from a no-op (a no-op already "
                "scores 1.000 on a local defect).")
        else:
            notes.append(
                "On the actual local repair task, quality stays at the no-op "
                "baseline (0.000): the model does not repair specificity even "
                "when it can infill a clean block. Do not read c_edit on local "
                "defects as a repair result; a no-op already scores 1.000 "
                "there.")
    if ability_rises and not cross_repair_rises:
        notes.append(
            "On the actual cross-block task, c_edit stays at its no-op floor: "
            "clean-block infill ability does not transfer to revising every "
            "editable block against a locked intro. The editor is above the "
            "infill floor and still below the repair floor.")
    if ability_rises and not partial_repair_rises:
        notes.append(
            "On the partial cross-block task (wrong thesis on a strict "
            "majority of editable blocks), c_edit stays below 0.2. This is the "
            "hardest distractor: a majority-vote heuristic sides with the "
            "corruption, so success requires using the locked intro as the "
            "anchor.")
    notes.append(
        "Byte-identical restore is reported as a diagnostic only. A "
        "masked-diffusion infill regenerates the span, so exact copy is ~0 by "
        "construction and cannot be the precondition for interpreting the "
        "repair grid. exp4 now gates on on-thesis output and reports both.")

    write_result("exp7_editor_floor", {
        "experiment": "exp7_editor_floor",
        "preset": args.preset, "seed": args.seed, "n": n,
        "split": args.split,
        "preregistered_prediction": PREDICTION,
        "budgets": [{"stage_a": a, "stage_b": b} for a, b in budgets],
        "conditions": rows,
        "summary": {
            "ability_rises_with_budget": bool(ability_rises),
            "specificity_rises": bool(specificity_rises),
            "local_repair_rises": bool(local_repair_rises),
            "cross_repair_rises": bool(cross_repair_rises),
            "partial_repair_rises": bool(partial_repair_rises),
            "best_budget": best["budget"],
            "best_on_thesis": best["on_thesis"],
            "copy_fidelity_is_not_a_gate": True,
        },
        "notes": notes,
    })
    print("\n" + "\n".join(f"  ! {x}" for x in notes))
    return 0


if __name__ == "__main__":
    sys.exit(main())
